test('owner-only data, atomic content lock, and independent stock updates', async () => {
  product = { _id: id, title: 'Original', price: 100, sku: 'AL-1', isActive: true, inStock: true, automationLocked: true, ownerInfo: { supplier: 'Supplier', purchaseCost: 60, costIncludesVat: true } };
  assert.equal(productForViewer(product).ownerInfo, undefined);
  const publicResult = await request(`/${id}`, undefined, null, 'GET');
  assert.equal(publicResult.status, 200);
  assert.equal(publicResult.body.ownerInfo, undefined);
  assert.equal(publicResult.body.automationLocked, undefined);
  assert.equal((await request(`/owner/${id}`, undefined, 'other', 'GET')).status, 403);
  assert.equal((await request(`/owner/${id}`, { purchaseCost: 1 }, 'other')).status, 403);
  assert.equal((await request(`/owner/${id}`, { price: 1 })).status, 400);
  assert.equal((await request(`/owner/${id}`, { purchaseCost: -1 })).status, 400);
  assert.equal((await request(`/${id}/edit`, { price: 200 })).status, 423);
  assert.equal((await request(`/${id}`, undefined, 'owner', 'DELETE')).status, 423);
  assert.equal((await request(`/${id}/toggle`, {})).status, 423);
  assert.equal((await request(`/${id}/stock`, { inStock: false, price: 1 })).status, 400);
  const stock = await request(`/${id}/stock`, { inStock: false });
  assert.equal(stock.status, 200);
  assert.equal(stock.body.inStock, false);
  assert.equal(stock.body.automationLocked, true);
  assert.equal(stock.body.ownerInfo.purchaseCost, 60);
  assert.equal(product.price, 100);
  assert.equal(product.title, 'Original');
  assert.equal((await request(`/${id}/stock`, { inStock: true }, 'other')).body.ownerInfo, undefined);
  assert.equal(product.inStock, true);
  assert.equal((await request(`/owner/${id}`, { purchaseCost: 0 })).body.ownerInfo.purchaseCost, 0);
  assert.equal((await request(`/owner/${id}`, { purchaseCost: null })).body.ownerInfo.purchaseCost, null);
  assert.equal((await request(`/owner/${id}`, { automationLocked: false })).status, 200);
  assert.equal((await request(`/${id}/edit`, { price: 200 })).status, 200);
  assert.equal(product.price, 200);
  const importRow = { sku: 'AL-1', supplier: 'Verified supplier', purchaseCost: 65, costIncludesVat: true };
  assert.equal((await request('/owner/import', { rows: [importRow] }, 'other')).status, 403);
  assert.equal((await request('/owner/import', { rows: [{ ...importRow, price: 1 }] })).status, 400);
  assert.equal((await request('/owner/import', { rows: [importRow, importRow] })).status, 400);
  product.automationLocked = true;
  const lockedImport = await request('/owner/import', { rows: [importRow] });
  assert.equal(lockedImport.status, 200);
  assert.equal(lockedImport.body.results[0].status, 'locked-or-missing');
  assert.equal(product.ownerInfo.purchaseCost, null);
  product.automationLocked = false;
  const imported = await request('/owner/import', { rows: [importRow, { ...importRow, sku: 'unknown' }] });
  assert.equal(imported.status, 200);
  assert.equal(imported.body.results[0].status, 'saved');
  assert.equal(imported.body.results[1].status, 'missing');
  assert.equal(product.ownerInfo.purchaseCost, 65);
  assert.equal(product.price, 200);
  assert.equal(product.title, 'Original');
  assert.equal(product.inStock, true);

});
test('storefront costs require the designated owner and never enter the public catalog', async () => {
  product = { _id: id, title: 'Example', price: 100, isActive: true, ownerInfo: { supplier: 'Private supplier', purchaseCost: 60, costIncludesVat: true }, automationLocked: true };
  let filter;
  Product.find = input => { filter = input; return query([structuredClone(product)]); };
  assert.equal((await request('/owner/storefront', undefined, null, 'GET')).status, 401);
  assert.equal((await request('/owner/storefront', undefined, 'other', 'GET')).status, 403);
  const customer = await fetch(url + '/owner/storefront', { headers: { Authorization: `Bearer ${signToken({ userId: 'customer', role: 'user' })}` } });
  assert.equal(customer.status, 403);
  const response = await fetch(url + '/owner/storefront', { headers: { Authorization: `Bearer ${signToken({ userId: 'owner', role: 'admin' })}` } });
  assert.equal(response.status, 200);
  assert.match(response.headers.get('cache-control'), /no-store/);
  assert.deepEqual(await response.json(), { costs: [{ productId: id, purchaseCost: 60, costIncludesVat: true }] });
  assert.deepEqual(filter, { isActive: true });
  product.ownerInfo.purchaseCost = 0;
  assert.equal((await request('/owner/storefront', undefined, 'owner', 'GET')).body.costs[0].purchaseCost, 0);
  const publicResult = await request('/', undefined, null, 'GET');
  assert.equal(publicResult.status, 200);
  assert.equal(JSON.stringify(publicResult.body).includes('purchaseCost'), false);
  assert.equal(JSON.stringify(publicResult.body).includes('Private supplier'), false);
  delete product.ownerInfo;
  assert.deepEqual((await request('/owner/storefront', undefined, 'owner', 'GET')).body.costs[0], { productId: id, purchaseCost: null, costIncludesVat: false });
});
